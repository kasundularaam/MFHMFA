import { useEffect, useRef, useState } from 'react';
import { Plus, Sparkles, X } from 'lucide-react';

export interface StudioTab {
  id: string;
  tabKey: string;
  title: string;
  code: string;
  origin: 'user' | 'agent' | 'shared';
  unread: boolean;
  isWelcome?: boolean;
  zoom: number | null;
  pan: { x: number; y: number };
}

interface TabBarProps {
  tabs: StudioTab[];
  activeTabId: string;
  onSelectTab: (tabId: string) => void;
  onCloseTab: (tabId: string) => void;
  onNewTab: () => void;
  onRenameTab: (tabId: string, nextTitle: string) => void;
}

export function TabBar({
  tabs,
  activeTabId,
  onSelectTab,
  onCloseTab,
  onNewTab,
  onRenameTab,
}: TabBarProps) {
  const stripRef = useRef<HTMLDivElement | null>(null);
  const [editingId, setEditingId] = useState<string | null>(null);
  const [draftTitle, setDraftTitle] = useState('');
  const inputRef = useRef<HTMLInputElement | null>(null);

  useEffect(() => {
    if (editingId && inputRef.current) {
      inputRef.current.focus();
      inputRef.current.select();
    }
  }, [editingId]);

  useEffect(() => {
    const activeEl = stripRef.current?.querySelector(
      `[data-tab-id="${CSS.escape(activeTabId)}"]`
    ) as HTMLElement | null;
    activeEl?.scrollIntoView({ block: 'nearest', inline: 'nearest' });
  }, [activeTabId, tabs.length]);

  const commitRename = (tabId: string) => {
    const trimmed = draftTitle.trim();
    if (trimmed) {
      onRenameTab(tabId, trimmed);
    }
    setEditingId(null);
  };

  return (
    <div
      className="tabbar"
      role="tablist"
      aria-label="Diagram tabs"
      onWheel={(e) => {
        if (stripRef.current && Math.abs(e.deltaY) > Math.abs(e.deltaX)) {
          stripRef.current.scrollLeft += e.deltaY;
        }
      }}
    >
      <div ref={stripRef} className="tabbar-strip">
        {tabs.map((tab) => {
          const isActive = tab.id === activeTabId;
          const isEditing = editingId === tab.id;

          return (
            <div
              key={tab.id}
              data-tab-id={tab.id}
              role="tab"
              aria-selected={isActive}
              tabIndex={0}
              className={`editor-tab ${isActive ? 'active' : ''} ${tab.unread ? 'unread' : ''}`}
              onClick={() => onSelectTab(tab.id)}
              onDoubleClick={() => {
                setEditingId(tab.id);
                setDraftTitle(tab.title);
              }}
              onMouseDown={(e) => {
                // Middle-click closes tab just like VS Code
                if (e.button === 1) {
                  e.preventDefault();
                  onCloseTab(tab.id);
                }
              }}
              onKeyDown={(e) => {
                if (!isEditing && (e.key === 'Enter' || e.key === ' ')) {
                  e.preventDefault();
                  onSelectTab(tab.id);
                }
              }}
              title={`${tab.title}${tab.origin === 'agent' ? ' (Generated by Agent)' : ''} — Double-click to rename`}
            >
              {tab.unread ? (
                <span className="tab-unread-dot" aria-label="New update" />
              ) : tab.origin === 'agent' ? (
                <Sparkles size={11} className="tab-origin-icon" />
              ) : null}

              {isEditing ? (
                <input
                  ref={inputRef}
                  className="tab-rename-input"
                  value={draftTitle}
                  onChange={(e) => setDraftTitle(e.target.value)}
                  onClick={(e) => e.stopPropagation()}
                  onBlur={() => commitRename(tab.id)}
                  onKeyDown={(e) => {
                    e.stopPropagation();
                    if (e.key === 'Enter') commitRename(tab.id);
                    if (e.key === 'Escape') setEditingId(null);
                  }}
                />
              ) : (
                <span className="tab-label">{tab.title}</span>
              )}

              <button
                type="button"
                className="tab-close-btn"
                aria-label={`Close ${tab.title}`}
                title="Close tab"
                onClick={(e) => {
                  e.stopPropagation();
                  onCloseTab(tab.id);
                }}
              >
                <X size={12} />
              </button>
            </div>
          );
        })}

        <button
          type="button"
          className="tab-add-btn"
          onClick={onNewTab}
          title="New diagram tab"
          aria-label="New diagram tab"
        >
          <Plus size={14} />
        </button>
      </div>
    </div>
  );
}
